import WebSocket from 'ws';
import { startServer } from './index';
const srv = await startServer({ port: 47890, udpPort: 47891 });
const profile = { name: 'Host', carId: 'ember', paint: null, look: {} };
const a = new WebSocket('ws://127.0.0.1:47890/play');
a.on('open', () => a.send(JSON.stringify({ t: 'hello', game: 'RMR_race', proto: 1, join: 'create', settings: { name: 'Test', maxPlayers: 4, mode: 'race', mapId: 'city', laps: 1, items: true }, profile })));
a.on('message', (d) => console.log('A <', String(d).slice(0, 200)));
await new Promise((r) => setTimeout(r, 300));
const roomId = [...srv.manager.rooms.keys()][0];
const b = new WebSocket('ws://127.0.0.1:47890/play');
b.on('open', () => b.send(JSON.stringify({ t: 'hello', game: 'RMR_race', proto: 1, join: 'join', roomId, profile: { ...profile, name: 'Guest' } })));
b.on('message', (d) => console.log('B <', String(d).slice(0, 120)));
const ag = new WebSocket('ws://127.0.0.1:47890/agent');
ag.on('open', () => ag.send(JSON.stringify({ t: 'watch' })));
ag.on('message', (d) => console.log('AG <', String(d).slice(0, 300)));
await new Promise((r) => setTimeout(r, 800));
const r = await fetch('http://127.0.0.1:47890/api/rooms'); console.log('HTTP', (await r.text()).slice(0, 200));
await srv.close(); process.exit(0);
